// Langget puts the languages a project lists into one of its packages, for go-mc26's package lang:
// English is built into go-mc26; langget adds the others a project wants, some or all of them.
//
// The list is the file mc26-langs in the package's directory — locales, one or more a line ("cs_cz de_de"),
// or "all"; # starts a comment — or the environment variable MC26_LANGS, which wins. For each language
// langget fetches its file by the checksum go-mc26's lang.Manifest has for it (so exactly this Minecraft
// version's), checks it, and writes <locale>.lang and langs_gen.go, which embeds them and registers them
// with package lang when the package is imported; a language no longer listed is removed. With no list, or
// an empty one, langs_gen.go has no language: English alone. A project may commit what langget writes, or
// ignore it (and mc26-langs) in git and run langget where it builds.
//
// In the package that should hold the languages:
//
//	//go:generate go run github.com/mj41/go-mc26/cmd/langget
//
// then go generate, and chat.SetLocale("cs_cz"). The files come from go-mc26-lang's blobs (-base), or from
// a directory of them (-from: a checkout of that branch, for a build without the network). After an upgrade
// of go-mc26 to another Minecraft version, go generate again: package lang refuses another version's files.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/mj41/go-mc26/data/lang"
)

// DefaultBase is where the language files are by their checksum: go-mc26-lang's blobs.
const DefaultBase = "https://raw.githubusercontent.com/mj41/go-mc26-lang/blobs"

const generated = "langs_gen.go"

func main() {
	dir := flag.String("dir", ".", "the package's directory")
	pkg := flag.String("pkg", os.Getenv("GOPACKAGE"), "its package name (go generate sets $GOPACKAGE)")
	base := flag.String("base", DefaultBase, "the URL the files are under, by checksum (<base>/<sha256>.lang)")
	from := flag.String("from", "", "a directory of the files by checksum instead of -base (a checkout of go-mc26-lang's blobs)")
	flag.Parse()
	g := getter{Dir: *dir, Pkg: *pkg, Base: *base, From: *from, Manifest: lang.Manifest, Version: lang.Version,
		Client: &http.Client{Timeout: 2 * time.Minute}} // a stalled server must not hang go generate
	if err := g.run(); err != nil {
		fmt.Fprintln(os.Stderr, "langget:", err)
		os.Exit(1)
	}
}

// getter is a run of langget.
type getter struct {
	Dir, Pkg   string
	Base, From string
	Manifest   map[string]string // the checksums by locale (lang.Manifest)
	Version    string
	Client     *http.Client
	Log        io.Writer // nil: os.Stderr
}

func (g getter) logf(format string, args ...any) {
	w := g.Log
	if w == nil {
		w = os.Stderr
	}
	fmt.Fprintf(w, "langget: "+format+"\n", args...)
}

// wanted is the languages the project lists, en_us left out (go-mc26 has it), sorted.
func (g getter) wanted() ([]string, error) {
	list, ok := os.LookupEnv("MC26_LANGS")
	if !ok {
		data, err := os.ReadFile(filepath.Join(g.Dir, "mc26-langs"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		list = string(data)
	}
	set := map[string]bool{}
	for _, line := range strings.Split(list, "\n") {
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		for _, l := range strings.FieldsFunc(line, func(r rune) bool { return r == ' ' || r == ',' || r == '\t' || r == '\r' }) {
			if l == "all" {
				for m := range g.Manifest {
					set[m] = true
				}
				continue
			}
			if _, ok := g.Manifest[l]; !ok {
				return nil, fmt.Errorf("%q is no language of Minecraft %s", l, g.Version)
			}
			set[l] = true
		}
	}
	delete(set, "en_us")
	out := make([]string, 0, len(set))
	for l := range set {
		out = append(out, l)
	}
	sort.Strings(out)
	return out, nil
}

func (g getter) run() error {
	if g.Pkg == "" {
		return errors.New("no package name: run it from go generate, or give -pkg")
	}
	want, err := g.wanted()
	if err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, l := range want {
		keep[l+".lang"] = true
		if err := g.fetch(l); err != nil {
			return fmt.Errorf("%s: %w", l, err)
		}
	}
	// what an earlier run wrote and the list no longer has
	for l := range g.Manifest {
		if !keep[l+".lang"] {
			if err := os.Remove(filepath.Join(g.Dir, l+".lang")); err != nil && !errors.Is(err, os.ErrNotExist) {
				return err
			}
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go-mc26's langget from mc26-langs (Minecraft %s); DO NOT EDIT.\n\npackage %s\n", g.Version, g.Pkg)
	if len(want) == 0 {
		// the file stays, with nothing in it: go generate, still going through the package's files, would
		// fail on one removed under it
		b.WriteString("\n// No languages listed: English alone, built into go-mc26.\n")
		if err := writeAtomic(filepath.Join(g.Dir, generated), []byte(b.String())); err != nil {
			return err
		}
		g.logf("no languages listed: English alone (built into go-mc26)")
		return nil
	}
	b.WriteString("\n")
	b.WriteString("import (\n\t_ \"embed\"\n\n\t\"github.com/mj41/go-mc26/data/lang\"\n)\n")
	for _, l := range want {
		fmt.Fprintf(&b, "\n//go:embed %s.lang\nvar lang_%s []byte\n", l, l)
	}
	b.WriteString("\nfunc init() {\n")
	for _, l := range want {
		fmt.Fprintf(&b, "\tlang.MustRegister(%q, lang_%s)\n", l, l)
	}
	b.WriteString("}\n")
	if err := writeAtomic(filepath.Join(g.Dir, generated), []byte(b.String())); err != nil {
		return err
	}
	g.logf("%d languages of Minecraft %s: %s", len(want), g.Version, strings.Join(want, " "))
	return nil
}

// fetch writes the language's file into the package's directory, unless the one there is already it.
func (g getter) fetch(locale string) error {
	want := g.Manifest[locale]
	path := filepath.Join(g.Dir, locale+".lang")
	if have, err := os.ReadFile(path); err == nil && lang.Sum(have) == want {
		return nil
	}
	name := strings.TrimPrefix(want, "sha256:") + ".lang"
	var data []byte
	var err error
	if g.From != "" {
		data, err = os.ReadFile(filepath.Join(g.From, name))
	} else {
		data, err = g.download(g.Base + "/" + name)
	}
	if err != nil {
		return err
	}
	if got := lang.Sum(data); got != want {
		return fmt.Errorf("the file fetched is %s, not the %s Minecraft %s's has", got, want, g.Version)
	}
	return writeAtomic(path, data)
}

// writeAtomic writes a file whole or not at all: an interrupted run leaves no half file.
func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	_, err = tmp.Write(data)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(tmp.Name(), 0o644)
	}
	if err != nil {
		os.Remove(tmp.Name())
		return err
	}
	return os.Rename(tmp.Name(), path)
}

func (g getter) download(url string) ([]byte, error) {
	resp, err := g.Client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	// a language file is a megabyte or two: more is not one
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxFile+1))
	if err == nil && len(data) > maxFile {
		err = fmt.Errorf("%s: over %d MB, no language file", url, maxFile>>20)
	}
	return data, err
}

// maxFile is the most a language file may be.
const maxFile = 64 << 20

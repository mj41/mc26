// Package block is every block of this Minecraft version as a Go type
// (block.Stone{}, block.OakStairs{Facing: …}) and its state ids. FromID gives a
// block by name; ToStateID and StateList convert between a block with its
// properties and the StateID chunks and packets carry. Solid, CollisionShape,
// DestroySpeed and the other functions of a StateID answer what the game knows
// of a state.
package block

import (
	"bytes"
	"compress/gzip"
	_ "embed"
	"fmt"
	"math/bits"

	"github.com/mj41/go-mc26/nbt"
)

// Block is a block with its properties, one Go type per block of this version;
// ID is its resource location ("minecraft:stone").
type Block interface {
	ID() string
}

// This file stores all possible block states into a TAG_List with gzip compressed.
// blocks.go, block_states.nbt, and properties_enum.go are generated by gen-blocks
// (an external generator).
//
//go:embed block_states.nbt
var blockStates []byte

var (
	// ToStateID gives the state id of a block with its properties.
	ToStateID map[Block]StateID
	// StateList gives the block, with its properties, of a state id.
	StateList []Block
)

// BitsPerBlock indicates how many bits are needed to represent all possible
// block states. This value is used to determine the size of the global palette.
var BitsPerBlock int

type (
	// StateID is a block state's id: what chunks and packets carry for a block.
	StateID int
	// State is a block state by name and properties, as NBT carries it.
	State struct {
		Name       string
		Properties nbt.RawMessage
	}
)

func (s *State) Block() (Block, error) {
	// Get an empty Block object
	block, ok := FromID[s.Name]
	if !ok {
		return nil, UnknownBlockErr{s.Name}
	}

	// Set property values
	if s.Properties.Type != nbt.TagEnd {
		err := s.Properties.Unmarshal(&block)
		if err != nil {
			return nil, err
		}
	}
	return block, nil
}

type UnknownBlockErr struct {
	Name string
}

func (u UnknownBlockErr) Error() string {
	return "unknown block: " + u.Name
}

func init() {
	var states []State
	// decompress
	z, err := gzip.NewReader(bytes.NewReader(blockStates))
	if err != nil {
		panic(err)
	}
	// decode all states
	if _, err = nbt.NewDecoder(z).Decode(&states); err != nil {
		panic(err)
	}
	ToStateID = make(map[Block]StateID, len(states))
	StateList = make([]Block, 0, len(states))
	for _, state := range states {
		block, err := state.Block()
		if err != nil {
			panic(err)
		}
		if _, ok := ToStateID[block]; ok {
			panic(fmt.Errorf("state %#v already exists", block))
		}
		ToStateID[block] = StateID(len(StateList))
		StateList = append(StateList, block)
	}
	BitsPerBlock = bits.Len(uint(len(StateList)))
}

// Package langmods writes the languages a go-mc26 library does not carry as the modules of go-mc26-lang,
// one per language, and releases them into a checkout of that repository:
//
//   - branch mc-<version>: a directory per language (cs-cz/: go.mod, cs_cz.go, cs_cz.lang), module
//     github.com/mj41/go-mc26-lang/<dir>, its package holding the file (Data), its locale, the Minecraft
//     version and the file's checksum (Sum, as go-mc26's lang.Manifest has it);
//   - tags <dir>/v0.<YYN>.<n>: a language's module at a version, made when its file changed since its last
//     tag of that version (the first release tags every language, a later one only those that changed);
//   - branch blobs: every file by its checksum (<sha256>.lang), only ever added to — what langget fetches.
//
// The files are generate.LangFiles's: the bytes the library's manifest was made of.
package langmods

import (
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/mj41/mc26/gen/internal/generate"
	"github.com/mj41/mc26/gen/internal/gitx"
)

// Module is the module path prefix: a language's module is Module/<dir>.
const Module = "github.com/mj41/go-mc26-lang"

// BlobsBase is where the files are by their checksum, published (go-mc26-lang's blobs): where langget
// fetches them from.
const BlobsBase = "https://raw.githubusercontent.com/mj41/go-mc26-lang/blobs"

// Options of a write or a release.
type Options struct {
	DataDir   string // the extraction: <DataDir>/lang/*.json
	Version   string // the Minecraft version ("26.3")
	TagBase   string // the version line of the tags ("v0.263.")
	OutDir    string // where Write puts the modules
	Generator string // recorded in the commit message (the mc26 commit)
	Log       func(string, ...any)
}

// Dir is a locale's directory and module name: cs_cz → cs-cz.
func Dir(locale string) string { return strings.ReplaceAll(locale, "_", "-") }

// Write writes every language but en_us (built into go-mc26) as a module under o.OutDir, and the branch's
// README; it returns the files by locale.
func Write(o Options) (map[string][]byte, error) {
	files, err := generate.LangFiles(o.DataDir)
	if err != nil {
		return nil, err
	}
	delete(files, "en_us")
	if err := os.RemoveAll(o.OutDir); err != nil {
		return nil, err
	}
	locales := sortedKeys(files)
	var index strings.Builder
	for _, l := range locales {
		dir := filepath.Join(o.OutDir, Dir(l))
		sum := generate.LangSum(files[l])
		write := func(name, content string) error { return writeFile(filepath.Join(dir, name), []byte(content)) }
		if err := write("go.mod", fmt.Sprintf("module %s/%s\n\ngo 1.25\n", Module, Dir(l))); err != nil {
			return nil, err
		}
		if err := writeFile(filepath.Join(dir, l+".lang"), files[l]); err != nil {
			return nil, err
		}
		name := languageName(files[l])
		if err := write(l+".go", source(l, name, o.Version, sum)); err != nil {
			return nil, err
		}
		fmt.Fprintf(&index, "| `%s` | %s | `%s` |\n", Dir(l), name, sum[:len("sha256:")+12])
	}
	readme := fmt.Sprintf(`# go-mc26-lang — Minecraft %[1]s

The languages of Minecraft: Java Edition %[1]s that [go-mc26](https://github.com/mj41/go-mc26) does not
carry (it has English built in), one Go module per language, each holding the language's file for go-mc26's
package lang. Generated by [mc26](https://github.com/mj41/mc26); never edited by hand.

`+"```"+`
go get %[2]s/cs-cz@%[3]s<n>        # the newest tag of the language for Minecraft %[1]s
`+"```"+`

`+"```go"+`
import (
	"github.com/mj41/go-mc26/chat"
	"github.com/mj41/go-mc26/data/lang"
	cs_cz "%[2]s/cs-cz"
)

lang.MustRegister(cs_cz.Locale, cs_cz.Data) // refused unless the file is this version's (lang.Manifest)
chat.SetLocale(cs_cz.Locale)
`+"```"+`

Or let go-mc26's langget write the languages a project lists (some, or "all") into one of its packages, by
their checksums: see go-mc26's package lang.

| module | language | checksum |
|---|---|---|
%[4]s`, o.Version, Module, o.TagBase, index.String())
	if err := writeFile(filepath.Join(o.OutDir, "README.md"), []byte(readme)); err != nil {
		return nil, err
	}
	o.log("langmods: %d languages of %s written to %s", len(locales), o.Version, o.OutDir)
	return files, nil
}

func source(locale, name, version, sum string) string {
	return fmt.Sprintf(`// Code generated by mc26 lang; DO NOT EDIT.

// Package %[1]s is Minecraft %[3]s's %[1]s translations (%[2]s): a language file for go-mc26's package lang.
//
//	lang.MustRegister(%[1]s.Locale, %[1]s.Data)
//	chat.SetLocale(%[1]s.Locale)
package %[1]s

import _ "embed"

// Locale is the language's locale, as the game names it.
const Locale = %[1]q

const (
	// Version is the Minecraft version the file is of.
	Version = %[3]q
	// Sum is the file's checksum: the one go-mc26's lang.Manifest has for the locale at that version.
	Sum = %[4]q
)

// Data is the language's .lang file.
//
//go:embed %[1]s.lang
var Data []byte
`, locale, name, version, sum)
}

// languageName is the language's own name and region ("Čeština (Česko)"), from its file.
func languageName(data []byte) string {
	fields := strings.Split(string(data), "\x00")
	m := map[string]string{}
	for i := 0; i+1 < len(fields); i += 2 {
		m[fields[i]] = fields[i+1]
	}
	name, region := m["language.name"], m["language.region"]
	switch {
	case name == "":
		return "?"
	case region == "":
		return name
	}
	return name + " (" + region + ")"
}

// Release commits the modules Write made into the go-mc26-lang checkout repo — the branch mc-<version>, the
// blobs — and tags each language whose file changed since its last tag of the version line. Nothing is
// pushed. It returns the tags it made.
func Release(o Options, repo string, files map[string][]byte) ([]string, error) {
	if clean, err := gitx.IsClean(repo); err != nil || !clean {
		return nil, fmt.Errorf("langmods: %s is not a clean checkout (%v)", repo, err)
	}
	start := strings.TrimSpace(must(gitx.Run(repo, "rev-parse", "--abbrev-ref", "HEAD")))
	defer gitx.Run(repo, "checkout", "-q", start)

	// the files by checksum
	if !gitx.BranchExists(repo, "blobs") {
		if _, err := gitx.Run(repo, "checkout", "-q", "--orphan", "blobs"); err != nil {
			return nil, err
		}
		if _, err := gitx.Run(repo, "rm", "-rqf", "--cached", "."); err != nil {
			return nil, err
		}
		if err := clearTree(repo); err != nil {
			return nil, err
		}
		if err := writeFile(filepath.Join(repo, "README.md"), []byte("# go-mc26-lang blobs\n\nEvery language file of every Minecraft version, named by its checksum (`<sha256>.lang`), as\ngo-mc26's lang.Manifest lists them: what go-mc26's langget fetches. Only ever added to.\n")); err != nil {
			return nil, err
		}
	} else if err := gitx.Checkout(repo, "blobs", ""); err != nil {
		return nil, err
	}
	added := 0
	for _, l := range sortedKeys(files) {
		path := filepath.Join(repo, strings.TrimPrefix(generate.LangSum(files[l]), "sha256:")+".lang")
		if _, err := os.Stat(path); err == nil {
			continue
		}
		if err := writeFile(path, files[l]); err != nil {
			return nil, err
		}
		added++
	}
	if _, _, err := gitx.Commit(repo, fmt.Sprintf("Minecraft %s's language files by checksum (%d new)", o.Version, added)); err != nil {
		return nil, err
	}

	// the modules
	branch := "mc-" + o.Version
	if err := gitx.Checkout(repo, branch, "main"); err != nil {
		return nil, err
	}
	if err := gitx.ReplaceTree(repo, o.OutDir); err != nil {
		return nil, err
	}
	commit, _, err := gitx.Commit(repo, fmt.Sprintf("Minecraft %s's languages, %d modules (mc26 %s)", o.Version, len(files), o.Generator))
	if err != nil {
		return nil, err
	}

	var tags []string
	for _, l := range sortedKeys(files) {
		dir := Dir(l)
		last, err := gitx.Tags(repo, dir+"/"+o.TagBase+"*")
		if err != nil {
			return nil, err
		}
		if len(last) > 0 {
			if _, err := gitx.Run(repo, "diff", "--quiet", lastTag(last), commit, "--", dir); err == nil {
				continue // the language's module is as its last tag has it
			}
		}
		tag, err := gitx.NextTag(repo, dir+"/"+o.TagBase)
		if err != nil {
			return nil, err
		}
		msg := fmt.Sprintf("%s of Minecraft %s (%s)", l, o.Version, generate.LangSum(files[l]))
		if _, err := gitx.Run(repo, "tag", "-a", tag, "-m", msg, commit); err != nil {
			return nil, err
		}
		tags = append(tags, tag)
	}
	o.log("langmods: %s at %s, %d tags", branch, commit[:12], len(tags))
	return tags, nil
}

// lastTag is the highest patch of tags of one line (Tags sorts them as text: v0.263.10 before v0.263.2).
func lastTag(tags []string) string {
	best, bestN := tags[0], -1
	for _, t := range tags {
		var n int
		if _, err := fmt.Sscanf(t[strings.LastIndex(t, ".")+1:], "%d", &n); err == nil && n > bestN {
			best, bestN = t, n
		}
	}
	return best
}

func clearTree(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.Name() != ".git" {
			if err := os.RemoveAll(filepath.Join(dir, e.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

func sortedKeys(m map[string][]byte) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func must(s string, err error) string {
	if err != nil {
		return ""
	}
	return s
}

func (o Options) log(format string, args ...any) {
	if o.Log != nil {
		o.Log(format, args...)
	}
}

// Missing returns the languages of files (English aside: go-mc26 carries it) whose file is not under base
// (<base>/<sha256>.lang), sorted: what a go-mc26 release's manifest would name but langget could not fetch.
// An answer but found or not found is an error, not a missing file.
func Missing(client *http.Client, base string, files map[string][]byte) ([]string, error) {
	var missing []string
	for _, l := range sortedKeys(files) {
		if l == "en_us" {
			continue
		}
		url := base + "/" + strings.TrimPrefix(generate.LangSum(files[l]), "sha256:") + ".lang"
		resp, err := client.Head(url)
		if err != nil {
			return nil, err
		}
		resp.Body.Close()
		switch resp.StatusCode {
		case http.StatusOK:
		case http.StatusNotFound:
			missing = append(missing, l)
		default:
			return nil, fmt.Errorf("%s: %s", url, resp.Status)
		}
	}
	return missing, nil
}

// Package report measures a built library tree: how much of it the generators
// wrote (per generator), how much is hand-written (per origin recorded in
// COPIED: byte-identical to upstream, modified, new) and how that splits over
// the packages — plus the size of the machinery that produces it.
package report

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/tabwriter"
)

// Options selects what to measure.
type Options struct {
	LibDir  string // a built library tree (has COPIED)
	GenRoot string // the gen/ directory, for the machinery counts; "" skips them
}

type count struct{ files, lines int }

func (c *count) add(lines int) { c.files++; c.lines += lines }

// Result holds the measurements.
type Result struct {
	Generated map[string]*count    // by generator file name
	Hand      map[string]*count    // by origin: upstream, modified, new, (unlisted)
	ByDir     map[string]*[2]count // top-level dir → [generated, hand-written]
	Other     count                // non-Go generated data (block_states.nbt)
	GenGo     count                // gen/ Go code (cmd + internal)
	Java      count                // data-gen/java
	HandInput map[string]int       // hand-crafted input files → entries
	Overlays  map[string]*count    // src/_versions/<v>
}

// Run measures o.LibDir.
func Run(o Options) (*Result, error) {
	r := &Result{
		Generated: map[string]*count{}, Hand: map[string]*count{}, ByDir: map[string]*[2]count{},
		HandInput: map[string]int{}, Overlays: map[string]*count{},
	}
	origins, err := readCopied(filepath.Join(o.LibDir, "COPIED"))
	if err != nil {
		return nil, err
	}
	err = filepath.WalkDir(o.LibDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(o.LibDir, path)
		if d.IsDir() {
			if rel != "." && (strings.HasPrefix(d.Name(), ".") || strings.HasPrefix(d.Name(), "_")) {
				return filepath.SkipDir
			}
			return nil
		}
		top := strings.SplitN(rel, string(filepath.Separator), 2)[0]
		if !strings.Contains(rel, string(filepath.Separator)) {
			top = "(root)"
		}
		dir := r.ByDir[top]
		if dir == nil {
			dir = &[2]count{}
			r.ByDir[top] = dir
		}
		switch {
		case strings.HasSuffix(rel, ".go"):
			lines, gen := goFile(path)
			if gen != "" {
				c := r.Generated[gen]
				if c == nil {
					c = &count{}
					r.Generated[gen] = c
				}
				c.add(lines)
				dir[0].add(lines)
				return nil
			}
			origin := origins[rel]
			if origin == "" {
				origin = "unlisted"
			}
			c := r.Hand[origin]
			if c == nil {
				c = &count{}
				r.Hand[origin] = c
			}
			c.add(lines)
			dir[1].add(lines)
		case strings.HasSuffix(rel, ".nbt"):
			r.Other.add(0)
			dir[0].files++
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if o.GenRoot != "" {
		if err := machinery(o.GenRoot, r); err != nil {
			return nil, err
		}
	}
	return r, nil
}

// goFile returns the line count and, for a generated file, the generator
// named in its "Code generated by gen/<file> …" header.
func goFile(path string) (lines int, generator string) {
	f, err := os.Open(path)
	if err != nil {
		return 0, ""
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 64*1024*1024)
	first := true
	for sc.Scan() {
		lines++
		if first {
			first = false
			line := sc.Text()
			if strings.Contains(line, "Code generated") && strings.Contains(line, "DO NOT EDIT") {
				generator = "other"
				if i := strings.Index(line, "gen/"); i >= 0 {
					name := line[i+4:]
					if j := strings.IndexAny(name, " ;"); j >= 0 {
						name = name[:j]
					}
					generator = name
				}
			}
		}
	}
	return lines, generator
}

func readCopied(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("not a built library (no COPIED): %w", err)
	}
	origins := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if p, o, ok := strings.Cut(line, "\t"); ok {
			origins[p] = o
		}
	}
	return origins, nil
}

func machinery(genRoot string, r *Result) error {
	countGo := func(dir string, into *count) error {
		return filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
				return err
			}
			n, _ := goFile(path)
			into.add(n)
			return nil
		})
	}
	if err := countGo(filepath.Join(genRoot, "cmd"), &r.GenGo); err != nil {
		return err
	}
	if err := countGo(filepath.Join(genRoot, "internal"), &r.GenGo); err != nil {
		return err
	}
	javaDir := filepath.Join(filepath.Dir(genRoot), "data-gen", "java")
	entries, _ := os.ReadDir(javaDir)
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".java") {
			data, err := os.ReadFile(filepath.Join(javaDir, e.Name()))
			if err != nil {
				return err
			}
			r.Java.add(bytes.Count(data, []byte("\n")))
		}
	}
	hc, _ := os.ReadDir(filepath.Join(genRoot, "hand-crafted"))
	for _, e := range hc {
		if strings.HasSuffix(e.Name(), ".json") {
			data, err := os.ReadFile(filepath.Join(genRoot, "hand-crafted", e.Name()))
			if err != nil {
				return err
			}
			// entries ≈ top-level keys of an object or elements of an array
			r.HandInput[e.Name()] = topLevelEntries(data)
		}
	}
	versions, _ := os.ReadDir(filepath.Join(genRoot, "src", "_versions"))
	for _, v := range versions {
		if v.IsDir() {
			c := &count{}
			if err := countGo(filepath.Join(genRoot, "src", "_versions", v.Name()), c); err != nil {
				return err
			}
			r.Overlays[v.Name()] = c
		}
	}
	return nil
}

// topLevelEntries counts the keys of a JSON object or the elements of an
// array; a hand-crafted file is one of the two.
func topLevelEntries(data []byte) int {
	var obj map[string]json.RawMessage
	if err := json.Unmarshal(data, &obj); err == nil {
		// keys starting with "_" are comments; a file whose values are all objects or
		// arrays (naming_overrides.json) counts the entries one level down
		nested, total, plain := true, 0, 0
		for k, v := range obj {
			if strings.HasPrefix(k, "_") {
				continue
			}
			plain++
			var inner map[string]json.RawMessage
			var list []json.RawMessage
			switch {
			case json.Unmarshal(v, &inner) == nil:
				total += len(inner)
			case json.Unmarshal(v, &list) == nil:
				total += len(list)
			default:
				nested = false
			}
		}
		if nested {
			return total
		}
		return plain
	}
	var list []json.RawMessage
	if err := json.Unmarshal(data, &list); err == nil {
		return len(list)
	}
	return 0
}

// Print writes the report as text.
func (r *Result) Print(w io.Writer, version string) {
	tw := tabwriter.NewWriter(w, 0, 4, 2, ' ', 0)
	genFiles, genLines := 0, 0
	for _, c := range r.Generated {
		genFiles += c.files
		genLines += c.lines
	}
	handFiles, handLines := 0, 0
	for _, c := range r.Hand {
		handFiles += c.files
		handLines += c.lines
	}
	fmt.Fprintf(tw, "go-mc26 %s\tfiles\tlines\n", version)
	fmt.Fprintf(tw, "generated\t%d\t%d\n", genFiles, genLines)
	for _, k := range sortedKeys(r.Generated) {
		fmt.Fprintf(tw, "  %s\t%d\t%d\n", k, r.Generated[k].files, r.Generated[k].lines)
	}
	if r.Other.files > 0 {
		fmt.Fprintf(tw, "  data files (.nbt)\t%d\t\n", r.Other.files)
	}
	fmt.Fprintf(tw, "hand-written\t%d\t%d\n", handFiles, handLines)
	for _, k := range []string{"upstream", "modified", "new", "unlisted"} {
		if c := r.Hand[k]; c != nil {
			fmt.Fprintf(tw, "  %s\t%d\t%d\n", k, c.files, c.lines)
		}
	}
	if genLines+handLines > 0 {
		fmt.Fprintf(tw, "generated share of lines\t\t%.1f%%\n", 100*float64(genLines)/float64(genLines+handLines))
		if lang := r.Generated["gen_lang.go"]; lang != nil {
			g := genLines - lang.lines
			fmt.Fprintf(tw, "  without the translations\t\t%.1f%% (%d generated vs %d hand-written lines)\n", 100*float64(g)/float64(g+handLines), g, handLines)
		}
	}
	fmt.Fprintln(tw)
	fmt.Fprintf(tw, "package\tgenerated files\tgenerated lines\thand files\thand lines\n")
	for _, k := range sortedKeys(r.ByDir) {
		d := r.ByDir[k]
		if d[0].files+d[1].files == 0 {
			continue
		}
		fmt.Fprintf(tw, "%s\t%d\t%d\t%d\t%d\n", k, d[0].files, d[0].lines, d[1].files, d[1].lines)
	}
	if r.GenGo.files > 0 || r.Java.files > 0 {
		fmt.Fprintln(tw)
		fmt.Fprintf(tw, "machinery\tfiles\tlines\n")
		fmt.Fprintf(tw, "gen (Go: commands, generators, build, tests harness)\t%d\t%d\n", r.GenGo.files, r.GenGo.lines)
		fmt.Fprintf(tw, "data-gen/java (extractors)\t%d\t%d\n", r.Java.files, r.Java.lines)
		for _, k := range sortedKeys(r.HandInput) {
			fmt.Fprintf(tw, "hand-crafted/%s\t\t%d entries\n", k, r.HandInput[k])
		}
		for _, k := range sortedKeys(r.Overlays) {
			fmt.Fprintf(tw, "src/_versions/%s (overlay)\t%d\t%d\n", k, r.Overlays[k].files, r.Overlays[k].lines)
		}
	}
	tw.Flush()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
